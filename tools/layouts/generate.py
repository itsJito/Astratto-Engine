"""Astratto Engine - writes layouts.cpp: a program that prints the size of every structure in the public C headers and
the offset of each of its fields, as the compiler lays them out. Hand-written bindings are checked against its output
(the Java bindings also ask the library itself for every size, through astratto_layout, when they load it).

    python tools/layouts/generate.py
    cl /nologo /std:c++17 /I native/include tools/layouts/layouts.cpp /Fe:layouts.exe && layouts.exe
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
INCLUDE = os.path.join(HERE, '..', '..', 'native', 'include', 'astratto')


def structs(text):
    text = re.sub(r'/\*.*?\*/', '', text, flags=re.S)
    for m in re.finditer(r'typedef struct (\w+)\s*\{(.*?)\}\s*(\w+);', text, flags=re.S):
        name, body = m.group(3), m.group(2)
        fields = []
        for decl in body.split(';'):
            decl = decl.strip()
            if not decl:
                continue
            if '(' in decl:  # a function pointer
                fm = re.search(r'\(\s*\*\s*(\w+)\s*\)', decl)
                if fm:
                    fields.append(fm.group(1))
                continue
            decl = re.sub(r'\[[^\]]*\]', '', decl)
            parts = decl.split(',')
            fields.append(parts[0].split()[-1].lstrip('*'))
            fields.extend(p.strip().lstrip('*') for p in parts[1:])
        yield name, fields


def main():
    text = ''
    for h in ('astratto.h', 'astratto_module.h'):
        with open(os.path.join(INCLUDE, h), encoding='utf-8') as f:
            text += f.read()
    out = ['// Astratto Engine - prints the size of every structure in astratto.h and the offset of each of its fields, as the',
           '// compiler lays them out. Generated by tools/layouts/generate.py: regenerate it when the header changes.',
           '#include <cstddef>', '#include <cstdio>', '#include "astratto/astratto.h"', '#include "astratto/astratto_module.h"', '',
           'int main() {']
    for name, fields in structs(text):
        out.append(f'    std::printf("{name} %u\\n", static_cast<unsigned>(sizeof({name})));')
        for f in fields:
            out.append(f'    std::printf("  {f} %u\\n", static_cast<unsigned>(offsetof({name}, {f})));')
    out.append('    return 0;\n}\n')
    with open(os.path.join(HERE, 'layouts.cpp'), 'w', encoding='utf-8') as f:
        f.write('\n'.join(out))


if __name__ == '__main__':
    main()
